    #[test]
    fn recording_session_insert_captures_one_undo_group() {
        let mut app = setup_recording_app();
        spawn_clip(&mut app, 7, "Key Light");
        insert_active_timeline(
            &mut app,
            46,
            vec![Track {
                id: "track-1".to_string(),
                label: "Track 1".to_string(),
                muted: false,
                solo: false,
                expanded: false,
                actions: Vec::new(),
                automation_lanes: Vec::new(),
            }],
        );
        app.world_mut()
            .resource_mut::<TimelineRecordingStates>()
            .set(46, true, Some("track-1".to_string()));

        app.world_mut()
            .write_message(EngineActionEnvelope::detached(ClipAction::Start(
                IdExpr::Single(7),
            )));
        app.update();
        app.world_mut()
            .write_message(EngineActionEnvelope::detached(ClipAction::Stop(
                IdExpr::Single(7),
            )));
        app.update();
        app.world_mut()
            .write_message(timecode_command(TimecodeCommand::StopTimecode(46)));
        app.update();

        nightfall_undo::dispatcher::process_pending_actions(app.world_mut());
        app.world_mut()
            .resource_mut::<UndoManager>()
            .finalize_detached_groups();

        let undo_manager = app.world().resource::<UndoManager>();
        assert_eq!(undo_manager.undo_depth(), 1);
        let group = undo_manager
            .peek_undo()
            .expect("recorded insert should create an undo group");
        assert_eq!(group.entries.len(), 1);

        let inverse = group.entries[0]
            .command
            .as_any()
            .downcast_ref::<TimelineCommand>()
            .expect("inverse should be a timeline command");
        let TimelineCommand::StoreTimeline(timeline) = inverse else {
            panic!("expected store timeline inverse");
        };
        assert_eq!(timeline.identifiers.id, 46);
        let track = timeline
            .tracks
            .iter()
            .find(|track| track.id == "track-1")
            .expect("original target track should be restored");
        assert!(track.actions.is_empty());
    }
