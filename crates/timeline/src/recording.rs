/// Runtime recording state for one timeline.
#[derive(Debug, Clone, PartialEq, Eq, serde::Serialize, serde::Deserialize)]
#[typeshare::typeshare]
pub struct TimelineRecordingState {
    /// User-facing timeline ID.
    pub timeline_id: u32,
    /// Whether the timeline is armed for recording.
    pub enabled: bool,
    /// Track that receives recorded actions.
    pub target_track_id: Option<String>,
}

/// Runtime recording state for all timelines.
#[derive(Resource, Default, Debug, Clone)]
pub struct TimelineRecordingStates {
    states: HashMap<u32, TimelineRecordingState>,
}

impl TimelineRecordingStates {
    /// Set the full recording state for a timeline.
    pub fn set(&mut self, timeline_id: u32, enabled: bool, target_track_id: Option<String>) {
        self.states.insert(
            timeline_id,
            TimelineRecordingState {
                timeline_id,
                enabled,
                target_track_id,
            },
        );
    }

    /// Set only the target track for a timeline, preserving enabled state.
    pub fn set_target_track(&mut self, timeline_id: u32, target_track_id: Option<String>) {
        let state = self
            .states
            .entry(timeline_id)
            .or_insert(TimelineRecordingState {
                timeline_id,
                enabled: false,
                target_track_id: None,
            });
        state.target_track_id = target_track_id;
    }

    /// Disable recording for a timeline while preserving the selected target track.
    pub fn disable(&mut self, timeline_id: u32) {
        let state = self
            .states
            .entry(timeline_id)
            .or_insert(TimelineRecordingState {
                timeline_id,
                enabled: false,
                target_track_id: None,
            });
        state.enabled = false;
    }

    /// Remove all runtime state for a timeline.
    pub fn remove(&mut self, timeline_id: u32) {
        self.states.remove(&timeline_id);
    }

    /// Return the state for a timeline.
    pub fn get(&self, timeline_id: u32) -> Option<&TimelineRecordingState> {
        self.states.get(&timeline_id)
    }

    /// Return all states sorted by timeline ID for stable websocket output.
    pub fn sorted_states(&self) -> Vec<TimelineRecordingState> {
        let mut states = self.states.values().cloned().collect::<Vec<_>>();
        states.sort_by_key(|state| state.timeline_id);
        states
    }
}

/// Runtime identities generated by timeline playback itself.
#[derive(Resource, Default, Debug)]
pub struct TimelineCommandOrigins {
    clip_undo_ids: HashSet<Uuid>,
    clip_operation_ids: HashSet<OperationId>,
}

impl TimelineCommandOrigins {
    /// Mark a legacy clip undo identity as timeline-originated.
    pub fn mark_clip_undo_id(&mut self, undo_id: Uuid) {
        self.clip_undo_ids.insert(undo_id);
    }

    /// Whether a legacy clip undo identity was generated by timeline playback.
    pub fn is_timeline_clip_undo_id(&self, undo_id: Uuid) -> bool {
        self.clip_undo_ids.contains(&undo_id)
    }

    /// Mark a concrete clip action as timeline-originated.
    pub fn mark_clip_operation_id(&mut self, operation_id: OperationId) {
        self.clip_operation_ids.insert(operation_id);
    }

    /// Whether a concrete clip action was generated by timeline playback.
    pub fn is_timeline_clip_operation_id(&self, operation_id: OperationId) -> bool {
        self.clip_operation_ids.contains(&operation_id)
    }

    /// Clear all recorded origins after the recorder has consumed this frame.
    pub fn clear(&mut self) {
        self.clip_undo_ids.clear();
        self.clip_operation_ids.clear();
    }
}

/// In-progress recording state for one timeline capture session.
#[derive(Debug, Clone)]
struct TimelineRecordingSession {
    target_track_id: String,
    actions: Vec<Action>,
}

/// Actions staged by an active recording session for one timeline.
#[derive(Debug, Clone, serde::Serialize, serde::Deserialize)]
#[typeshare::typeshare]
pub struct TimelineRecordingPreview {
    /// User-facing timeline ID.
    pub timeline_id: u32,
    /// Track that receives recorded actions.
    pub target_track_id: String,
    /// Actions captured so far in the active recording session.
    pub actions: Vec<Action>,
}

/// Recorded actions accumulated for active recording sessions.
#[derive(Resource, Default, Debug)]
pub struct TimelineRecordingSessions {
    sessions: HashMap<u32, TimelineRecordingSession>,
}

impl TimelineRecordingSessions {
    fn target_track_id_for(
        &mut self,
        timeline_id: u32,
        target_track_id: Option<&str>,
        recording_states: &mut TimelineRecordingStates,
    ) -> String {
        if let Some(session) = self.sessions.get(&timeline_id) {
            return session.target_track_id.clone();
        }

        let track_id = target_track_id
            .map(str::to_string)
            .unwrap_or_else(|| format!("recorded-actions-{}", Uuid::new_v4().simple()));

        recording_states.set_target_track(timeline_id, Some(track_id.clone()));
        self.sessions.insert(
            timeline_id,
            TimelineRecordingSession {
                target_track_id: track_id.clone(),
                actions: Vec::new(),
            },
        );
        track_id
    }

    fn append_actions(&mut self, timeline_id: u32, target_track_id: String, actions: Vec<Action>) {
        self.sessions
            .entry(timeline_id)
            .or_insert(TimelineRecordingSession {
                target_track_id,
                actions: Vec::new(),
            })
            .actions
            .extend(actions);
    }

    fn take(&mut self, timeline_id: u32) -> Option<TimelineRecordingSession> {
        self.sessions.remove(&timeline_id)
    }

    pub fn remove(&mut self, timeline_id: u32) {
        self.sessions.remove(&timeline_id);
    }

    fn target_changed(&self, timeline_id: u32, target_track_id: Option<&str>) -> bool {
        let Some(session) = self.sessions.get(&timeline_id) else {
            return false;
        };
        target_track_id != Some(session.target_track_id.as_str())
    }

    /// Return all active session previews sorted by timeline ID for stable websocket output.
    pub fn sorted_previews(&self) -> Vec<TimelineRecordingPreview> {
        let mut previews = self
            .sessions
            .iter()
            .map(|(timeline_id, session)| TimelineRecordingPreview {
                timeline_id: *timeline_id,
                target_track_id: session.target_track_id.clone(),
                actions: session.actions.clone(),
            })
            .collect::<Vec<_>>();
        previews.sort_by_key(|preview| preview.timeline_id);
        previews
    }
}

/// Writes a detached clip action and marks it as timeline-originated.
pub fn write_timeline_clip_action(
    writer: &mut MessageWriter<EngineActionEnvelope<ClipAction>>,
    origins: &mut TimelineCommandOrigins,
    action: ClipAction,
) {
    let event = EngineActionEnvelope::detached(action);
    origins.mark_clip_operation_id(event.operation_id);
    writer.write(event);
}

/// Resource identifying which timeline is currently recording clip actions.
#[derive(Clone)]
struct ActiveRecordingTimeline {
    timeline_id: u32,
    position: Duration,
    target_track_id: String,
}

/// Clip action captured with timing metadata during timeline recording.
#[derive(Clone)]
struct RecordedClipAction {
    clip_label: String,
    action: ActionKind,
}

impl RecordedClipAction {
    fn label(&self) -> String {
        match &self.action {
            ActionKind::StartClip(_) => format!("Start Clip {}", self.clip_label),
            ActionKind::StopClip(_) => format!("Stop Clip {}", self.clip_label),
            ActionKind::AdvanceSequence(_) => {
                format!("Advance Sequence {}", self.clip_label)
            }
            ActionKind::BackSequence(_) => {
                format!("Back Sequence {}", self.clip_label)
            }
            ActionKind::SetClipRate { rate, .. } => {
                format!("Set {} Rate {}", self.clip_label, rate)
            }
            ActionKind::JumpToCue { cue_index, .. } => {
                format!("Jump {} to Cue {}", self.clip_label, cue_index)
            }
            ActionKind::FireCue(_) => {
                unreachable!("recorded clip actions are created from clip commands")
            }
            ActionKind::DeskEval(_) => {
                unreachable!("recorded clip actions are created from clip commands")
            }
            ActionKind::RegisteredAction(action) => {
                format!("Registered Action {}", action.id.as_str())
            }
        }
    }
}

fn rounded_duration_millis(duration: Duration) -> Duration {
    let millis = duration.as_millis().min(u128::from(u64::MAX)) as u64;
    Duration::from_millis(millis)
}

fn create_recorded_action(position: Duration, recorded_action: &RecordedClipAction) -> Action {
    Action {
        id: format!("recorded-{}", Uuid::new_v4().simple()),
        label: recorded_action.label(),
        position: rounded_duration_millis(position),
        duration: Duration::from_millis(1000),
        action: recorded_action.action.clone(),
    }
}

fn resolve_clip_action(
    clip_id: u32,
    make_action: impl FnOnce(Uuid) -> ActionKind,
    clip_lookup: &ClipLookupSnapshot,
) -> Option<RecordedClipAction> {
    let clip = match clip_lookup.by_id(clip_id) {
        Ok((_, clip)) => clip,
        Err(error) => {
            tracing::warn!(
                clip_id,
                ?error,
                "Skipping timeline recording for missing clip"
            );
            return None;
        }
    };

    let label = if clip.identifiers.label.trim().is_empty() {
        format!("Clip {}", clip.identifiers.id)
    } else {
        clip.identifiers.label.clone()
    };

    Some(RecordedClipAction {
        clip_label: label,
        action: make_action(clip.identifiers.uid),
    })
}

fn recorded_actions_from_clip_action(
    action: &ClipAction,
    clip_lookup: &ClipLookupSnapshot,
) -> Vec<RecordedClipAction> {
    let mut actions = Vec::new();
    match action {
        ClipAction::Start(id_expr)
        | ClipAction::StartAtTiming {
            clip_id: id_expr, ..
        } => {
            for id in id_expr.expand() {
                if let Some(action) = resolve_clip_action(id, ActionKind::StartClip, clip_lookup) {
                    actions.push(action);
                }
            }
        }
        ClipAction::Stop(id_expr)
        | ClipAction::StopAtTiming {
            clip_id: id_expr, ..
        } => {
            for id in id_expr.expand() {
                if let Some(action) = resolve_clip_action(id, ActionKind::StopClip, clip_lookup) {
                    actions.push(action);
                }
            }
        }
        ClipAction::Go(id_expr) => {
            for id in id_expr.expand() {
                if let Some(action) =
                    resolve_clip_action(id, ActionKind::AdvanceSequence, clip_lookup)
                {
                    actions.push(action);
                }
            }
        }
        ClipAction::Back(clip_id) => {
            for id in clip_id.expand() {
                if let Some(action) = resolve_clip_action(id, ActionKind::BackSequence, clip_lookup)
                {
                    actions.push(action);
                }
            }
        }
        ClipAction::SetRate { clip_id, rate } => {
            for id in clip_id.expand() {
                if let Some(action) = resolve_clip_action(
                    id,
                    |uid| ActionKind::SetClipRate { uid, rate: *rate },
                    clip_lookup,
                ) {
                    actions.push(action);
                }
            }
        }
        ClipAction::Goto {
            clip_id, position, ..
        }
        | ClipAction::RenderAt {
            clip_id, position, ..
        } => {
            for id in clip_id.expand() {
                if let Some(action) = resolve_clip_action(
                    id,
                    |uid| ActionKind::JumpToCue {
                        uid,
                        cue_index: *position,
                    },
                    clip_lookup,
                ) {
                    actions.push(action);
                }
            }
        }
    }
    actions
}

fn queue_recording_session_insert(
    timeline_id: u32,
    session: TimelineRecordingSession,
    pending_actions: &mut PendingEngineActionBuffer,
) {
    if session.actions.is_empty() {
        return;
    }

    pending_actions.push(DynEngineActionEnvelope::with_context(
        OperationId::new(),
        None,
        Some(UndoId::new()),
        Box::new(TimelineAction::InsertRecordedActions {
            timeline_id,
            track_id: session.target_track_id,
            actions: session.actions,
        }),
    ));
}

/// Record externally originated clip actions into armed timelines.
pub fn record_timeline_actions_system(
    mut clip_events: MessageReader<EngineActionEnvelope<ClipAction>>,
    command_origins: Res<TimelineCommandOrigins>,
    mut recording_states: ResMut<TimelineRecordingStates>,
    mut recording_sessions: ResMut<TimelineRecordingSessions>,
    timeline_query: Query<&MaterializedTimeline>,
    timecode_query: Query<&TimecodeGenerator>,
    clip_lookup: ClipLookup,
) {
    let mut timecode_times = HashMap::new();
    for timecode in timecode_query.iter() {
        timecode_times.insert(
            timecode.timecode.identifiers.uid,
            (timecode.state.current_time, timecode.state.is_active),
        );
    }

    let mut active_recording_timelines = Vec::new();
    for timeline in timeline_query.iter() {
        let timeline_id = timeline.timeline.identifiers.id;
        let Some(state) = recording_states.get(timeline_id).cloned() else {
            continue;
        };
        if !state.enabled || !timeline.is_active {
            continue;
        }
        let Some((timecode_time, timecode_active)) =
            timecode_times.get(&timeline.timeline.timecode_uid)
        else {
            continue;
        };
        if !timecode_active {
            continue;
        }
        let target_track_id = recording_sessions.target_track_id_for(
            timeline_id,
            state.target_track_id.as_deref(),
            &mut recording_states,
        );
        active_recording_timelines.push(ActiveRecordingTimeline {
            timeline_id,
            position: timeline.get_playback_position(*timecode_time),
            target_track_id,
        });
    }

    if active_recording_timelines.is_empty() {
        for _ in clip_events.read() {}
        return;
    }

    let clip_snapshot = clip_lookup.snapshot();
    let mut recorded_actions = Vec::new();
    for event in clip_events.read() {
        if command_origins.is_timeline_clip_operation_id(event.operation_id)
            || event
                .undo_id
                .is_some_and(|undo_id| command_origins.is_timeline_clip_undo_id(undo_id.into()))
        {
            continue;
        }
        recorded_actions.extend(recorded_actions_from_clip_action(
            &event.action,
            &clip_snapshot,
        ));
    }

    if recorded_actions.is_empty() {
        return;
    }

    for active_timeline in active_recording_timelines {
        let actions = recorded_actions
            .iter()
            .map(|action| create_recorded_action(active_timeline.position, action))
            .collect::<Vec<_>>();
        recording_sessions.append_actions(
            active_timeline.timeline_id,
            active_timeline.target_track_id,
            actions,
        );
    }
}

/// Finish recording sessions when playback stops, recording is disarmed, or target changes.
pub fn finish_timeline_recording_sessions_system(
    mut timecode_events: MessageReader<TimecodeEvent>,
    mut timeline_events: MessageReader<CommandEnvelope<TimelineCommand>>,
    mut timeline_actions: MessageReader<EngineActionEnvelope<TimelineAction>>,
    mut recording_states: ResMut<TimelineRecordingStates>,
    mut recording_sessions: ResMut<TimelineRecordingSessions>,
    mut pending_actions: ResMut<PendingEngineActionBuffer>,
) {
    let mut finish_timeline_ids = HashSet::new();
    let mut disable_timeline_ids = HashSet::new();

    for event in timecode_events.read() {
        match event {
            TimecodeEvent::Paused(timeline_id) | TimecodeEvent::Stopped(timeline_id) => {
                finish_timeline_ids.insert(*timeline_id);
                disable_timeline_ids.insert(*timeline_id);
            }
            TimecodeEvent::Started(_)
            | TimecodeEvent::Seeked { .. }
            | TimecodeEvent::Deleted(_) => {}
        }
    }

    for event in timeline_events.read() {
        match &event.command {
            TimelineCommand::StopTimeline(timeline_id) => {
                finish_timeline_ids.insert(*timeline_id);
                disable_timeline_ids.insert(*timeline_id);
            }
            TimelineCommand::SetTimelineRecording {
                timeline_id,
                enabled,
                target_track_id,
            } => {
                if !enabled
                    || recording_sessions.target_changed(*timeline_id, target_track_id.as_deref())
                {
                    finish_timeline_ids.insert(*timeline_id);
                }
                if !enabled {
                    disable_timeline_ids.insert(*timeline_id);
                }
            }
            _ => {}
        }
    }

    for event in timeline_actions.read() {
        if let TimelineAction::Stop(timeline_id) = event.action {
            finish_timeline_ids.insert(timeline_id);
            disable_timeline_ids.insert(timeline_id);
        }
    }

    for timeline_id in disable_timeline_ids {
        recording_states.disable(timeline_id);
    }

    for timeline_id in finish_timeline_ids {
        if let Some(session) = recording_sessions.take(timeline_id) {
            queue_recording_session_insert(timeline_id, session, &mut pending_actions);
        }
    }
}

/// Clear timeline-origin markers after recording has inspected this frame.
pub fn clear_timeline_command_origins(mut command_origins: ResMut<TimelineCommandOrigins>) {
    command_origins.clear();
}

