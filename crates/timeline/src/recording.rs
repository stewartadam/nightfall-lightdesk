    /// Wraps a timecode command with detached lifecycle context for recording tests.
    fn timecode_command(command: TimecodeCommand) -> TimecodeEvent {
        match command {
            TimecodeCommand::StartTimecode(id) => TimecodeEvent::Started(id),
            TimecodeCommand::PauseTimecode(id) => TimecodeEvent::Paused(id),
            TimecodeCommand::StopTimecode(id) => TimecodeEvent::Stopped(id),
            TimecodeCommand::SeekTimecode { id, position } => {
                TimecodeEvent::Seeked { id, position }
            }
            TimecodeCommand::DeleteTimecode(id) => TimecodeEvent::Deleted(id),
            TimecodeCommand::StoreTimecode(_) | TimecodeCommand::RenameTimecode { .. } => {
                panic!("CRUD commands are not runtime timecode events")
            }
        }
    }

    fn setup_recording_app() -> App {
        let mut app = App::new();
        app.add_message::<EngineActionEnvelope<ClipAction>>();
        app.add_message::<TimecodeEvent>();
        app.add_message::<CommandEnvelope<TimelineCommand>>();
        app.add_message::<EngineActionEnvelope<TimelineAction>>();
        app.init_resource::<TimelineRecordingStates>();
        app.init_resource::<TimelineRecordingSessions>();
        app.init_resource::<TimelineCommandOrigins>();
        app.init_resource::<PendingEngineActionBuffer>();
        app.init_resource::<UndoManager>();
        app.init_resource::<UndoRegistry>();
        app.insert_resource(DataProvider::<Timeline>::default());
        app.world_mut()
            .resource_mut::<UndoRegistry>()
            .register::<TimelineCommand>();
        app.world_mut()
            .resource_mut::<UndoRegistry>()
            .register_action::<TimelineAction>();
        app.add_systems(
            Update,
            (
                record_timeline_actions_system,
                finish_timeline_recording_sessions_system.after(record_timeline_actions_system),
            ),
        );
        app
    }

    fn spawn_clip(app: &mut App, id: u32, label: &str) -> Uuid {
        let uid = Uuid::new_v4();
        app.world_mut().spawn(Clip {
            identifiers: Identifiers {
                id,
                uid,
                label: label.to_string(),
            },
            source: None,
            ..Default::default()
        });
        uid
    }

    fn insert_active_timeline(app: &mut App, timeline_id: u32, tracks: Vec<Track>) -> Uuid {
        let timeline_uid = Uuid::new_v4();
        let mut timecode = TimecodeGenerator::default();
        timecode.timecode.identifiers.id = timeline_id;
        timecode.state.timecode_id = timeline_id;
        timecode.state.current_time = Duration::from_millis(1250);
        timecode.state.is_active = true;
        let timecode_uid = timecode.timecode.identifiers.uid;

        let timeline = Timeline {
            identifiers: Identifiers {
                id: timeline_id,
                uid: timeline_uid,
                label: format!("Timeline {}", timeline_id),
            },
            timecode_uid,
            tracks,
            ..Default::default()
        };
        app.world_mut()
            .resource_mut::<DataProvider<Timeline>>()
            .add(timeline.clone())
            .expect("timeline should store");

        let mut materialized = MaterializedTimeline::new(timeline);
        materialized.activate();
        app.world_mut().spawn(materialized);

        app.world_mut().spawn(timecode);

        timeline_uid
    }

    /// Stops or pauses recording and returns the queued internal persistence action.
    fn finish_recording_and_take_insert(
        app: &mut App,
        command: TimecodeCommand,
    ) -> Option<TimelineAction> {
        app.world_mut().write_message(timecode_command(command));
        app.update();

        let actions = app
            .world_mut()
            .resource_mut::<PendingEngineActionBuffer>()
            .drain();
        assert!(
            actions.len() <= 1,
            "recording stop should enqueue at most one action"
        );
        actions.into_iter().next().map(|action| {
            assert!(
                action.command_id.is_none(),
                "automatic recording persistence must not fabricate a user command"
            );
            assert!(
                action.undo_id.is_some(),
                "recording persistence should remain independently undoable"
            );
            *action
                .action
                .into_any()
                .downcast::<TimelineAction>()
                .expect("recording persistence should be a timeline action")
        })
    }

    /// Stops recording and returns the queued internal persistence action.
    fn stop_recording_and_take_insert(app: &mut App, timeline_id: u32) -> Option<TimelineAction> {
        finish_recording_and_take_insert(app, TimecodeCommand::StopTimecode(timeline_id))
    }

    #[test]
    fn records_start_clip_into_selected_track() {
        let mut app = setup_recording_app();
        let clip_uid = spawn_clip(&mut app, 7, "Key Light");
        insert_active_timeline(
            &mut app,
            42,
            vec![Track {
                id: "track-1".to_string(),
                label: "Track 1".to_string(),
                muted: false,
                solo: false,
                expanded: false,
                actions: Vec::new(),
                automation_lanes: Vec::new(),
            }],
        );
        app.world_mut()
            .resource_mut::<TimelineRecordingStates>()
            .set(42, true, Some("track-1".to_string()));

        app.world_mut()
            .write_message(EngineActionEnvelope::detached(ClipAction::Start(
                IdExpr::Single(7),
            )));
        app.update();

        let command = stop_recording_and_take_insert(&mut app, 42)
            .expect("recording stop should enqueue recorded actions");
        let TimelineAction::InsertRecordedActions {
            timeline_id,
            track_id,
            actions,
        } = command
        else {
            panic!("expected recorded insert command");
        };
        assert_eq!(timeline_id, 42);
        assert_eq!(track_id, "track-1");
        assert_eq!(actions.len(), 1);
        let action = &actions[0];
        assert_eq!(action.position, Duration::from_millis(1250));
        assert!(matches!(
            action.action,
            ActionKind::StartClip(uid) if uid == clip_uid
        ));
    }

